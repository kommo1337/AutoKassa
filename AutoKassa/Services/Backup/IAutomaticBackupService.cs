namespace AutoKassa.Services.Backup
{
    /// <summary>
    /// Координатор расписания резервного копирования.
    /// Сериализует стартовую, таймерную и внеочередную проверки локального (ISettingsService.RunAutoBackupIfDueAsync)
    /// и облачного (IYandexDiskBackupService) копирования; исключения рабочего цикла логируются внутри,
    /// чтобы один сбой не остановил расписание.
    /// </summary>
    public interface IAutomaticBackupService
    {
        /// <summary>
        /// Запустить координатор: немедленная проверка, затем периодическая раз в час.
        /// Идемпотентен — повторный вызов игнорируется. Не блокирует вызывающего поток.
        /// </summary>
        void Start();

        /// <summary>
        /// Разбудить координатор для внеочередной проверки (сохранение настроек, новое подключение).
        /// Запуск выполняется в фоне и не блокирует UI. Пока предыдущая внеочередная проверка
        /// выполняется, повторные вызовы схлопываются в одну ожидающую проверку (coalescing).
        /// </summary>
        void RequestCheck();

        /// <summary>
        /// Остановить таймер, отменить активную операцию и ограниченно дождаться её завершения.
        /// Вызывается при выходе из приложения до освобождения DI.
        /// </summary>
        /// <param name="timeout">Максимальное время ожидания; null — дефолт 10 секунд.</param>
        Task StopAsync(TimeSpan? timeout = null);
    }
}
